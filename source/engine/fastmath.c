float fastSin(float angle)
{
    // Normalizar a [0,360)
    angle = fmodf(angle, 360.0f);
    if (angle < 0.0f)
        angle += 360.0f;

    int quadrant = (int)(angle * (1.0f / 90.0f)); // 0..3
    float local  = angle - quadrant * 90.0f;      // 0..90

    // Clamp para evitar 90 exacto
    if (local >= 89.0f)
        local = 89.0f;

    int i = (int)local;        // 0..88
    float frac = local - i;    // 0..1

    float a, b;

    switch (quadrant)
    {
        case 0: // 0..90
            a = SIN90[i];
            b = SIN90[i + 1];
            return lerp(a, b, frac);

        case 1: // 90..180
            a = SIN90[89 - i];
            b = SIN90[88 - i];
            return lerp(a, b, frac);

        case 2: // 180..270
            a = SIN90[i];
            b = SIN90[i + 1];
            return -lerp(a, b, frac);

        default: // 270..360
            a = SIN90[89 - i];
            b = SIN90[88 - i];
            return -lerp(a, b, frac);
    }
}


float fastCos(float angle) {
    return fastSin(angle + 90.0f);
}

